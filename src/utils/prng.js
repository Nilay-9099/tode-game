// TODE AND THE LAST LILYPAD - Seeded PRNG for Daily Challenge (Spec Section 10)
// Uses Mulberry32 generator for fast 32-bit deterministic random numbers.

export function mulberry32(seed) {
  let s = seed | 0;
  return function () {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function getTodaySeedString() {
  const now = new Date();
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const d = String(now.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function hashStringToInt(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (Math.imul(31, hash) + str.charCodeAt(i)) | 0;
  }
  return hash;
}

export function createDailyRandom() {
  const seedStr = getTodaySeedString();
  const seedInt = hashStringToInt(seedStr);
  return {
    seedStr,
    seedInt,
    random: mulberry32(seedInt),
  };
}
